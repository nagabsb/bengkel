export const menuIconMap = Object.freeze({
    ...baseMenuIconMap,
    ...Object.fromEntries(
        Object.entries(menuIconAliases).map(([aliasName, baseName]) => [
            aliasName,
            baseMenuIconMap[baseName] || baseMenuIconMap.dashboard,
        ]),
    ),
});

export const resolveMenuIcon = (iconName) => menuIconMap[iconName] || menuIconMap.dashboard;

export const humanizeMenuIconLabel = (iconName) => String(iconName || '')
    .replaceAll('-', ' ')
    .replaceAll('_', ' ')
    .replace(/\b\w/g, (char) => char.toUpperCase());

export const menuIconOptions = Object.keys(baseMenuIconMap)
    .map((iconName) => ({
        value: iconName,
        label: humanizeMenuIconLabel(iconName),
        icon: iconName,
    }))
    .sort((left, right) => left.label.localeCompare(right.label, 'id'));
